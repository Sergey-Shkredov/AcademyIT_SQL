1. Какие столбцы обязательны, а какие можно не заполнять (по таблице orders)

Обязательные для заполнения (is_nullable = NO / NOT NULL):

order_id — уникальный идентификатор заказа (первичный ключ).
order_number — номер заказа (документа).
customer_id — клиент, оформивший заказ (заказ не может быть «ничьим»).
employee_id — сотрудник/менеджер, оформивший заказ.
order_date — дата создания/оформления заказа.
required_date — плановая дата, к которой клиент ожидает заказ.
status — текущий статус документа (новый, в обработке, отгружен и т.д.).
channel — канал продаж (опт, розничная сеть, дистрибьютор).

Можно не заполнять (is_nullable = YES / допускают NULL):

shipped_date — фактическая дата отгрузки клиенту.
comment — текстовое примечание (комментарий менеджера или клиента).
2. Почему shipped_date может быть пустым, а order_date — нет? О каком моменте процесса это говорит?
order_date (дата оформления) — фиксирует момент зарождения документа. Заказ создаётся «здесь и сейчас», поэтому дата известна сразу. Заказ не может существовать вне времени.
shipped_date (дата отгрузки) — фиксирует событие из будущего. В момент создания заказа товар ещё лежит на складе или только производится. Отгрузка ещё не произошла, поэтому точной фактической даты отгрузки в этот момент просто не существует в природе.
О чём это говорит с точки зрения бизнес-процесса:
Наличие NULL в shipped_date показывает текущий статус жизненного цикла: заказ находится на этапе обработки, согласования или комплектации на складе (либо был отменён до отгрузки).
Как только физическая передача товара перевозчику или клиенту состоялась, значение обновляется с NULL на фактическую дату.
*/


