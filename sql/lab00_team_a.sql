/*
Формат: «один <родитель> — много <потомок>: пояснение»

Один customers (клиент) — много orders (заказов):
Один заказ оформляется на одного конкретного клиента, но у одного клиента может быть множество заказов за всё время сотрудничества. (FK: orders.customer_id → customers.customer_id)

Один orders (заказ) — много order_items (позиций заказа):
Каждая строка/позиция относится строго к одному заказу, а в одном заказе покупателя может быть много разных позиций товаров. (FK: order_items.order_id → orders.order_id)

Один orders (заказ) — много invoices (счетов):
Один счёт на оплату выставляется по конкретному заказу, но к одному заказу может быть выставлено несколько счетов (например, при частичных отгрузках со склада). (FK: invoices.order_id → orders.order_id)

Один invoices (счёт) — много payments (оплат):
Каждый платёж поступает по конкретному счёту, но один счёт может оплачиваться несколькими платежами (например, предоплата 30% и доплата 70%). (FK: payments.invoice_id → invoices.invoice_id)

Один products (товар) — много price_history (история цен):
Каждая строка цены принадлежит конкретному товару, но у одного товара со временем появляется много записей с историческими и текущей ценами. (FK: price_history.product_id → products.product_id)

❓ Две таблицы, которые ссылаются сами на себя

Это таблицы employees и product_categories.

employees (ссылка manager_id → employee_id):

Что описывает: Иерархическую структуру компании (оргструктуру «руководитель — подчинённый»).
Руководитель — это такой же сотрудник из этой же таблицы, поэтому столбец manager_id ссылается на employee_id начальника. У генерального директора в этом поле стоит NULL.

product_categories (ссылка parent_category_id → category_id):

Что описывает: Двухуровневое дерево категорий товаров (классификатор продукции).
Дочерняя подкатегория (например, «Кефир») ссылается на родительскую категорию верхнего уровня (например, «Кисломолочная продукция»). У корневых категорий поле parent_category_id равно NUL
*/


