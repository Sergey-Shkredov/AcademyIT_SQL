О каком моменте процесса это говорит:

Наличие NULL в поле valid_to означает, что эта цена действует прямо сейчас (актуальный прайс).
Как только компания принимает решение изменить цену, в старой записи поле valid_to закрывается датой изменения, а для новой цены создаётся новая строка.
