-- ----------------------------------------------------------------------------
-- А2. Сколько это стоит в рублях
-- Для позиций из А1 вычислите сумму скидки сверх 10 % в рублях:
-- quantity * unit_price * (discount_pct - 10) / 100 (округлить до 2 знаков).
