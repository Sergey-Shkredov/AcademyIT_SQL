-- ----------------------------------------------------------------------------
-- А8. Крупнейшие счета и постраничный вывод (пагинация)
-- 1. Топ-10 счетов по сумме (с детерминированной сортировкой). Проверка: 1-е место — СЧ-2025-02646 (1 245 137,26).
