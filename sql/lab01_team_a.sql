OFFSET 10
FETCH  NEXT 10 ROWS ONLY;


-- ----------------------------------------------------------------------------
-- ★ А9. Keyset-пагинация (поиск без OFFSET)
-- Получить следующие 10 счетов после счета invoice_id = 2881 (сумма 875 376,40)
-- через сравнение кортежей: (amount, invoice_id) < (875376.40, 2881).
-- Проверка: 1-я строка — СЧ-2025-03817, 867 809,62.
-- ----------------------------------------------------------------------------
SELECT invoice_id,
       invoice_number,
       order_id,
       invoice_date,
       amount
FROM   invoices
WHERE  (amount, invoice_id) < (875376.40, 2881)
ORDER  BY amount DESC, 
          invoice_id DESC
FETCH  FIRST 10 ROWS ONLY;

-- Ответ на вопрос А9:
-- Почему направление сортировки обоих ключей должно совпадать (DESC, DESC)?
-- Оператор кортежного сравнения (amount, invoice_id) < (A, B) эквивалентен условию:
-- (amount < A) OR (amount = A AND invoice_id < B).
-- Это условие логически продолжает порядок строгого убывания как по сумме, так и по идентификатору.
-- Если направления сортировки различаются (например, DESC и ASC), сравнение кортежей сломается 
-- и вернет неверный набор строк при одинаковых суммах. Кроме того, совпадающие направления позволяют СУБД 
-- задействовать эффективный индексный поиск Index Scan без лишнего чтения диска.


-- ----------------------------------------------------------------------------
-- ★ А10. Цифра для руководства
-- Подсчет совокупных финансовых потерь от несанкционированных скидок:
-- ----------------------------------------------------------------------------
SELECT COUNT(*)                                                           AS items,
       ROUND(SUM(quantity * unit_price * discount_pct / 100), 2)          AS discount_total_rub,
       ROUND(SUM(quantity * unit_price * (discount_pct - 10) / 100), 2)   AS over_policy_rub
FROM   order_items
WHERE  discount_pct > 10;
