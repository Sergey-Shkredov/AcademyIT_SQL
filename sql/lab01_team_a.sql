-- Ответ на вопрос А4:
-- Почему в п. 4 не нужно отдельно писать AND shipped_date IS NOT NULL?
-- В SQL действует трёхзначная логика (3VL: TRUE, FALSE, UNKNOWN).
-- Любое сравнение с NULL (например, NULL > required_date) даёт результат UNKNOWN.
-- Предложение WHERE пропускает в результат только строки со значением TRUE.
-- Поэтому все строки с shipped_date IS NULL отфильтровываются автоматически.


