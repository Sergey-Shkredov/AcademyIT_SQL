-- ----------------------------------------------------------------------------
-- ★ А8. Сверка цен заказов с действующим прайс-листом (price_history)
-- Проверить, совпадает ли цена в заказе с прайсом на дату заказа.
-- Сколько позиций с расхождением? Что это говорит о причине убытков из А6?
-- ----------------------------------------------------------------------------
SELECT COUNT(*) AS price_mismatch_count
FROM   order_items   AS oi
JOIN   orders        AS o  ON o.order_id = oi.order_id
JOIN   price_history AS ph ON ph.product_id = oi.product_id 
                          AND o.order_date BETWEEN ph.valid_from 
                                               AND COALESCE(ph.valid_to, DATE '9999-12-31')
WHERE  oi.unit_price != ph.price;

-- Ответ на вопрос А8:
