-- ----------------------------------------------------------------------------
-- А6. Цена со скидкой против себестоимости (срез с 01.03.2025)
-- 1. Позиции заказов с 01.03.2025 (кроме отмененных) с отрицательной маржой.
--    Проверка: худшая маржа — -63,25 руб./шт. (-30,9 %).
-- 2. ★ Сумма прямых потерь. Проверка: 314 позиций, 3 661 609,00 руб.
-- ----------------------------------------------------------------------------
-- Запрос 1. Худшие по маржинальности сделки:
SELECT oi.order_item_id,
       oi.order_id,
       p.product_id,
       p.product_name,
       ROUND(oi.unit_price * (1 - oi.discount_pct / 100), 2)                       AS net_price,
       p.standard_cost,
       ROUND(oi.unit_price * (1 - oi.discount_pct / 100) - p.standard_cost, 2)     AS unit_margin_rub,
       ROUND(((oi.unit_price * (1 - oi.discount_pct / 100) - p.standard_cost) 
              / p.standard_cost * 100)::numeric, 1)                                AS margin_pct
FROM   order_items AS oi
JOIN   products    AS p ON p.product_id = oi.product_id
JOIN   orders      AS o ON o.order_id   = oi.order_id
WHERE  o.order_date >= DATE '2025-03-01'
  AND  o.status != 'Отменён'
  AND  oi.unit_price * (1 - oi.discount_pct / 100) < p.standard_cost
ORDER  BY unit_margin_rub ASC, oi.order_item_id ASC
FETCH  FIRST 10 ROWS ONLY;

-- Запрос 2 (★). Подсчет совокупных прямых убытков компании от отрицательной маржи:
SELECT COUNT(*)                                                                                     AS loss_items_count,
       ROUND(SUM(oi.quantity * (p.standard_cost - oi.unit_price * (1 - oi.discount_pct / 100))), 2) AS total_direct_loss_rub
FROM   order_items AS oi
JOIN   products    AS p ON p.product_id = oi.product_id
JOIN   orders      AS o ON o.order_id   = oi.order_id
WHERE  o.order_date >= DATE '2025-03-01'
  AND  o.status != 'Отменён'
  AND  oi.unit_price * (1 - oi.discount_pct / 100) < p.standard_cost;

