-- ----------------------------------------------------------------------------
-- А1. Очистка email адресов клиентов
-- 1. Выведите клиентов, у которых email отличается от LOWER(TRIM(email));
--    исходный email в скобках [email] и очищенный. Проверка: 32 строки.
-- 2. Одним запросом посчитайте: всего клиентов, клиентов с email, «грязных» email.
--    Проверка: 73 | 52 | 32.
-- 3. Вопрос: почему COUNT(email) не равен COUNT(*)?
-- ----------------------------------------------------------------------------
-- Запрос 1. Список клиентов с дефектными email (32 строки):
SELECT customer_id,
       customer_name,
       '[' || email || ']'   AS raw_email,
       LOWER(TRIM(email))    AS clean_email
FROM   customers
WHERE  email != LOWER(TRIM(email))
ORDER  BY customer_id;

-- Запрос 2. Сводная статистика качества контактных данных (73 | 52 | 32):
SELECT COUNT(*)                                              AS total_customers,
       COUNT(email)                                          AS customers_with_email,
       COUNT(*) FILTER (WHERE email != LOWER(TRIM(email)))   AS dirty_email_count
FROM   customers;

-- Ответ на вопрос А1:
-- COUNT(email) не равен COUNT(*), потому что стандартный агрегат COUNT(column_name) 
-- игнорирует строки со значением NULL (считает только непустые ячейки). 
-- У 21 клиента (73 - 52 = 21) email вообще не указан в базе (NULL). 
-- COUNT(*) считает физическое количество строк во всей таблице независимо от NULL.


-- ----------------------------------------------------------------------------
-- А2. Нормализация телефонных номеров клиентов
-- 1. Выведите уникальные маски формата телефона: regexp_replace(phone, '\d', '9', 'g').
--    Проверка: 4 формата.
-- 2. Приведите телефоны к виду +7XXXXXXXXXX.
-- 3. Проверьте отсутствие нарушений шаблона ^\+7\d{10}$. Проверка: 0 нарушений.
-- ----------------------------------------------------------------------------
-- Запрос 1. Определение масок существующих форматов (4 формата):
SELECT DISTINCT regexp_replace(phone, '\d', '9', 'g') AS phone_mask
FROM   customers
WHERE  phone IS NOT NULL
ORDER  BY phone_mask;

-- Запрос 2. Нормализация номеров к единому стандарту +7XXXXXXXXXX:
SELECT customer_id,
       customer_name,
       phone                                                      AS raw_phone,
       '+7' || RIGHT(regexp_replace(phone, '\D', '', 'g'), 10)    AS normalized_phone
FROM   customers
WHERE  phone IS NOT NULL
ORDER  BY customer_id;

-- Запрос 3. Проверка качества нормализации регулярным выражением (0 нарушений):
SELECT COUNT(*) AS invalid_phones_count
FROM  (
    SELECT '+7' || RIGHT(regexp_replace(phone, '\D', '', 'g'), 10) AS norm_phone
    FROM   customers
    WHERE  phone IS NOT NULL
) AS sub
WHERE  norm_phone !~ '^\+7\d{10}$';


