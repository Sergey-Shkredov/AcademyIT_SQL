-- ----------------------------------------------------------------------------
-- О2. Производственный календарь на декабрь 2025 года
-- Дата, день недели по-русски (to_char(d, 'TMDay')), 
-- признак «рабочий/выходной» через CASE и EXTRACT(ISODOW FROM d).
-- Проверка: 31 строка, 01.12.2025 — понедельник.
-- ----------------------------------------------------------------------------
SELECT d::date                                          AS calendar_date,
       TRIM(to_char(d, 'TMDay'))                        AS day_name,
       CASE 
           WHEN EXTRACT(ISODOW FROM d) IN (6, 7) THEN 'Выходной'
           ELSE 'Рабочий'
       END                                              AS day_type
FROM   generate_series(DATE '2025-12-01', DATE '2025-12-31', INTERVAL '1 day') AS d;


