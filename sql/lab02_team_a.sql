-- ----------------------------------------------------------------------------
-- А5. Просрочка оплаты и хронический должник
-- 1. Просрочка payment_date - due_date, класс срока. Топ-10 оплат с наибольшей просрочкой.
--    Проверка: максимальная просрочка — 90 дней.
-- 2. Оплаты с просрочкой > 30 дней и их концентрация на главном должнике.
--    Проверка: 231 и 13.
-- ----------------------------------------------------------------------------
-- Запрос 1. Топ-10 самых затянутых оплат в истории:
SELECT p.payment_id,
       p.payment_date,
       i.due_date,
       p.payment_date - i.due_date AS overdue_days,
       CASE 
           WHEN p.payment_date <= i.due_date      THEN 'в срок'
           WHEN p.payment_date - i.due_date <= 30 THEN 'до 30 дней'
           ELSE 'более 30 дней'
       END                         AS overdue_class,
       c.customer_id,
       c.customer_name,
       c.credit_limit
FROM   payments  AS p
JOIN   invoices  AS i ON i.invoice_id = p.invoice_id
JOIN   orders    AS o ON o.order_id   = i.order_id
JOIN   customers AS c ON c.customer_id = o.customer_id
ORDER  BY overdue_days DESC
FETCH  FIRST 10 ROWS ONLY;

-- Запрос 2. Общее число оплат с просрочкой > 30 дней и доля худшего клиента (231 и 13):
SELECT COUNT(*) FILTER (WHERE p.payment_date - i.due_date > 30) AS total_overdue_over_30_days,
       COUNT(*) FILTER (WHERE p.payment_date - i.due_date > 30 AND o.customer_id = 1) AS customer_1_overdue_over_30
FROM   payments AS p
JOIN   invoices AS i ON i.invoice_id = p.invoice_id
JOIN   orders   AS o ON o.order_id   = i.order_id;

