-- ----------------------------------------------------------------------------
-- А4. Сроки логистики и риск порчи скоропорта в Сибири
-- 1. Срок отгрузки в днях: shipped_date - order_date, регион клиента, класс срока.
--    Топ-10 самых долгих. Проверка: макс. срок 9 дней.
-- 2. Отгрузки 5+ дней отдельно для Сибири (регионы 9, 10) и остальных регионов.
--    Проверка: Сибирь — 869 из 932, остальные — 0 из 3310.
-- ----------------------------------------------------------------------------
-- Запрос 1. Топ-10 самых долгих отгрузок (максимальный срок — 9 дней):
SELECT o.order_id,
       o.order_number,
       c.customer_name,
       c.region_id,
       o.shipped_date - o.order_date AS shipping_days,
       CASE 
           WHEN o.shipped_date - o.order_date BETWEEN 1 AND 3 THEN '1–3 дня'
           WHEN o.shipped_date - o.order_date BETWEEN 4 AND 6 THEN '4–6 дней'
           ELSE '7+ дней'
       END                           AS duration_class
FROM   orders AS o
JOIN   customers AS c ON c.customer_id = o.customer_id
WHERE  o.shipped_date IS NOT NULL
ORDER  BY shipping_days DESC, o.order_id ASC
FETCH  FIRST 10 ROWS ONLY;

-- Запрос 2. Распределение длительности доставки по макрорегионам:
SELECT COUNT(*) FILTER (WHERE c.region_id IN (9, 10))                                          AS siberia_total_shipments,
       COUNT(*) FILTER (WHERE c.region_id IN (9, 10) AND (o.shipped_date - o.order_date) >= 5) AS siberia_5plus_days,
       COUNT(*) FILTER (WHERE c.region_id NOT IN (9, 10) OR c.region_id IS NULL)               AS other_total_shipments,
       COUNT(*) FILTER (WHERE (c.region_id NOT IN (9, 10) OR c.region_id IS NULL) 
                          AND (o.shipped_date - o.order_date) >= 5)                            AS other_5plus_days
FROM   orders AS o
JOIN   customers AS c ON c.customer_id = o.customer_id
WHERE  o.shipped_date IS NOT NULL;

